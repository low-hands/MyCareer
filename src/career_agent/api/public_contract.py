def _literals(model: type[BaseModel], field: str) -> tuple[str, ...]:
    """The closed set a field accepts, read from the model so the examples
    below cannot silently cover a subset of it."""

    annotation = model.model_fields[field].annotation
    # ``Literal[...] | None`` arrives as a Union; find the Literal arm wherever it sits.
    candidates = (annotation, *get_args(annotation))
    literals = [arm for arm in candidates if get_origin(arm) is Literal]
    if not literals:
        raise TypeError(f"{model.__name__}.{field} is not a Literal")
    return tuple(str(value) for value in get_args(literals[0]))


