def _wire(examples: list[BaseModel], *, mode: str) -> dict[str, Any]:
    # Responses are described as the server serialises them, so a field marked
    # ``exclude=True`` (``ContentDeltaEvent.delivery``) stays out of the wire
    # contract; requests are described as the server validates them.
    return {
        "schema": type(examples[0]).model_json_schema(mode=mode),
        "examples": [example.model_dump(mode="json") for example in examples],
    }


def public_contract() -> dict[str, Any]:
    stream_adapter: TypeAdapter[PublicStreamEvent] = TypeAdapter(PublicStreamEvent)
    return {
        "stream_events": {
            "schema": stream_adapter.json_schema(mode="serialization"),
            "examples": [
                stream_adapter.dump_python(event, mode="json")
                for event in _stream_event_examples()
            ],
        },
        "reads": {
            name: _wire(examples, mode="serialization")
            for name, examples in sorted(_read_examples().items())
        },
        "requests": {
            name: _wire(examples, mode="validation")
            for name, examples in sorted(_request_examples().items())
        },
    }


def render_public_contract() -> str:
    body = json.dumps(public_contract(), ensure_ascii=False, indent=2, sort_keys=True)
    return f"{_HEADER}\nexport const API_CONTRACT = {body} as const;\n"


def main(argv: list[str] | None = None) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    target = Path(arguments[0]) if arguments else CONTRACT_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_public_contract(), encoding="utf-8")
    print(f"wrote {target}")
    return 0


